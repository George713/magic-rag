import {test,expect} from '@playwright/test';

test('contextual followup shows standalone topic and keeps explicit filters, then falls back visibly',async ({page}) => {
 await page.goto('/');
 await page.getByLabel('Red',{exact:true}).check();
 await page.getByLabel('Creature',{exact:true}).check();
 await page.getByLabel('Maximum mana value',{exact:true}).fill('2');
 await page.getByLabel('Your question').fill('Find artifact-sacrifice creatures');
 await page.getByRole('button',{name:'Send',exact:true}).click();
 const first=page.locator('section.turn').nth(0);
 await first.locator('.retrieval-details > summary').click();
 await expect(first.getByTestId('actual-query')).toHaveText('Find artifact-sacrifice creatures');
 await page.getByLabel('Your question').fill('Any cheaper ones?');
 await page.getByRole('button',{name:'Send',exact:true}).click();
 const second=page.locator('section.turn').nth(1);
 await second.locator('.retrieval-details > summary').click();
 await expect(second.getByTestId('actual-query')).toHaveText('Atog artifact sacrifice cheaper creatures');
 await expect(second.getByTestId('original-question')).toHaveText('Any cheaper ones?');
 await expect(second.getByTestId('rewrite-status')).toHaveText('rewritten');
 await expect(second.getByTestId('rewrite-message')).toContainText('Explicit filters are unchanged');
 await expect(page.getByLabel('Red',{exact:true})).toBeChecked();
 await expect(page.getByLabel('Maximum mana value',{exact:true})).toHaveValue('2');
 await expect(second.getByRole('heading',{name:'Atog',exact:true})).toBeVisible();
 await page.getByLabel('Your question').fill('simulate rewrite failure');
 await page.getByRole('button',{name:'Send',exact:true}).click();
 const third=page.locator('section.turn').nth(2);
 await third.locator('.retrieval-details > summary').click();
 await expect(third.getByTestId('actual-query')).toHaveText('simulate rewrite failure');
 await expect(third.getByTestId('rewrite-status')).toHaveText('unavailable');
 await expect(third.getByTestId('rewrite-message')).toContainText('as-is');
 await page.getByLabel('Your question').fill('Atog');
 await page.getByRole('button',{name:'Send',exact:true}).click();
 const fourth=page.locator('section.turn').nth(3);
 await fourth.locator('.retrieval-details > summary').click();
 await expect(fourth.getByRole('heading',{name:'Atog',exact:true})).toBeVisible();
 await page.reload();
 await page.getByRole('button',{name:'Open conversation: Find artifact-sacrifice creatures',exact:true}).first().click();
 const reopened=page.locator('section.turn').nth(1);
 await reopened.locator('.retrieval-details > summary').click();
 await expect(reopened.getByTestId('original-question')).toHaveText('Any cheaper ones?');
 await expect(reopened.getByTestId('actual-query')).toHaveText('Atog artifact sacrifice cheaper creatures');
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
 await page.screenshot({path:'test-results/rewriting-mobile.png',fullPage:true});
});
